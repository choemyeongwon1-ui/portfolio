// ==========================================
// 글자 다듬기
// ------------------------------------------
// 화면에 그릴 때만 이모지·장식 문자를 걷어 낸다. (데이터 자체는 그대로 둔다.)
// ==========================================

export function plain(value) {
  return String(value ?? '')
    .replace(/[\p{Extended_Pictographic}\u{FE0F}\u{200D}\u{2726}]/gu, '')
    .replace(/\s+/g, ' ')
    .trim();
}
